// SHA-1 and the SHA-2 family.
//
// A signature is a number computed over a digest, so a verifier with no
// digest is nothing. There is no crate here, so these are written out:
// SHA-1 and SHA-256 over 32-bit words, SHA-384 and SHA-512 over 64-bit
// ones, straight from FIPS 180-4. They are compared against openssl dgst
// over the corpus and over a sweep of lengths either side of the block
// boundary, because padding is where a hand-written digest goes wrong.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Alg {
    Sha1,
    Sha256,
    Sha384,
    Sha512,
}

impl Alg {
    pub fn name(&self) -> &'static str {
        match self {
            Alg::Sha1 => "sha1",
            Alg::Sha256 => "sha256",
            Alg::Sha384 => "sha384",
            Alg::Sha512 => "sha512",
        }
    }

    pub fn len(&self) -> usize {
        match self {
            Alg::Sha1 => 20,
            Alg::Sha256 => 32,
            Alg::Sha384 => 48,
            Alg::Sha512 => 64,
        }
    }

    pub fn from_name(s: &str) -> Option<Alg> {
        match s {
            "sha1" => Some(Alg::Sha1),
            "sha256" => Some(Alg::Sha256),
            "sha384" => Some(Alg::Sha384),
            "sha512" => Some(Alg::Sha512),
            _ => None,
        }
    }
}

pub fn digest(alg: Alg, data: &[u8]) -> Vec<u8> {
    match alg {
        Alg::Sha1 => sha1(data).to_vec(),
        Alg::Sha256 => sha256(data).to_vec(),
        Alg::Sha384 => sha512_family(data, true),
        Alg::Sha512 => sha512_family(data, false),
    }
}

// The length padding both families use: a 0x80 byte, zeros, then the bit
// length. The only difference is the width of that length field.
fn pad(len: usize, block: usize, lenfield: usize) -> Vec<u8> {
    let bits = (len as u128) * 8;
    let mut tail = vec![0x80u8];
    while (len + tail.len() + lenfield) % block != 0 {
        tail.push(0);
    }
    let be = bits.to_be_bytes();
    tail.extend_from_slice(&be[16 - lenfield..]);
    tail
}

pub fn sha1(data: &[u8]) -> [u8; 20] {
    let mut h: [u32; 5] = [0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476, 0xC3D2E1F0];
    let mut msg = data.to_vec();
    msg.extend_from_slice(&pad(data.len(), 64, 8));
    for block in msg.chunks(64) {
        let mut w = [0u32; 80];
        for i in 0..16 {
            w[i] = u32::from_be_bytes([
                block[i * 4],
                block[i * 4 + 1],
                block[i * 4 + 2],
                block[i * 4 + 3],
            ]);
        }
        for i in 16..80 {
            w[i] = (w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16]).rotate_left(1);
        }
        let (mut a, mut b, mut c, mut d, mut e) = (h[0], h[1], h[2], h[3], h[4]);
        for (i, wi) in w.iter().enumerate() {
            let (f, k) = match i / 20 {
                0 => ((b & c) | ((!b) & d), 0x5A827999u32),
                1 => (b ^ c ^ d, 0x6ED9EBA1),
                2 => ((b & c) | (b & d) | (c & d), 0x8F1BBCDC),
                _ => (b ^ c ^ d, 0xCA62C1D6),
            };
            let t = a
                .rotate_left(5)
                .wrapping_add(f)
                .wrapping_add(e)
                .wrapping_add(k)
                .wrapping_add(*wi);
            e = d;
            d = c;
            c = b.rotate_left(30);
            b = a;
            a = t;
        }
        h[0] = h[0].wrapping_add(a);
        h[1] = h[1].wrapping_add(b);
        h[2] = h[2].wrapping_add(c);
        h[3] = h[3].wrapping_add(d);
        h[4] = h[4].wrapping_add(e);
    }
    let mut out = [0u8; 20];
    for (i, v) in h.iter().enumerate() {
        out[i * 4..i * 4 + 4].copy_from_slice(&v.to_be_bytes());
    }
    out
}

